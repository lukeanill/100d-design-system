const rel = (p) => path.relative(ROOT, p).split(path.sep).join("/")
const walk = (dir, test, out = []) => {
  for (const name of fs.readdirSync(dir)) {
    if (name === "node_modules" || name === "dist") continue
    const full = path.join(dir, name)
    const stat = fs.statSync(full)
    if (stat.isDirectory()) walk(full, test, out)
    else if (test(full)) out.push(full)
  }
  return out
}
const write = (file, text) => {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, text.replace(/\n{3,}/g, "\n\n").trimEnd() + "\n")
}
const GENERATED = "<!-- Generated by scripts/generate.mjs from the source. Do not edit by hand: change the source, then re-run the script. -->"
const esc = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ")

