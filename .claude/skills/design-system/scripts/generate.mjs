const COLOR_PREFIXES = ["bg", "text", "border", "ring", "fill", "stroke", "from", "to", "via", "outline", "decoration", "caret", "accent", "divide", "shadow", "border-t", "border-b", "border-l", "border-r", "ring-offset"]

// token usage: which component files use each token (sampled)
function scanUsage() {
  const files = walk(SRC, (f) => /\.(tsx|ts)$/.test(f) && !/\.(stories|test)\./.test(f) && f.includes(`${path.sep}components${path.sep}`))
  const usage = new Map() // key -> Map(file -> count)
  const add = (key, file) => {
    if (!usage.has(key)) usage.set(key, new Map())
    const m = usage.get(key)
    m.set(file, (m.get(file) ?? 0) + 1)
  }
  for (const f of files) {
    const text = fs.readFileSync(f, "utf8")
    const short = path.basename(f).replace(/\.tsx?$/, "")
    for (const m of text.matchAll(/--([a-z0-9][a-z0-9-]*)/g)) add(m[1], short)
    for (const m of text.matchAll(/(?<![\w-])((?:[a-z0-9\[\]()&>*_=-]+:)*)(-?[a-z]+(?:-[a-z]+)?)-(\(?--)?([a-z0-9][a-z0-9-]*)(\/[0-9.]+)?(?![\w-])/g)) {
      const prefix = m[2], name = m[4]
      if (COLOR_PREFIXES.includes(prefix) || prefix === "text" || prefix === "font") add(name, short)
      if (prefix === "rounded") add(`radius-${name}`, short)
      if (prefix === "shadow") add(`shadow-${name}`, short)
    }
    for (const m of text.matchAll(/\b(text-(?:xs|sm|md|lg|xl|[2-7]xl|base|action-(?:sm|md|lg)|label-(?:sm|md|lg)|h[1-6]-(?:pri|sec)(?:-bold)?|(?:xs|sm|md|lg)-(?:bold|italic)))\b/g)) add(m[1], short)
  }
  return usage
}

function usageOf(usage, name) {
  const base = name.replace(/^--/, "")
  const keys = [base]
  if (base.startsWith("color-")) keys.push(base.slice(6))
  if (base.startsWith("radius-")) keys.push(base)
  const seen = new Map()
  for (const k of keys) for (const [f, n] of usage.get(k) ?? []) seen.set(f, (seen.get(f) ?? 0) + n)
  const top = [...seen.entries()].sort((a, b) => b[1] - a[1]).slice(0, 3).map(([f]) => f)
  return { count: seen.size, top }
}

