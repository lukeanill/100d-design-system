// Transpile the typed theme definitions to plain modules in a temp folder so they can be imported.
async function loadThemes() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "ds-themes-"))
  const srcDir = path.join(SRC, "themes")
  for (const f of fs.readdirSync(srcDir)) {
    if (!f.endsWith(".ts") || f.endsWith(".test.ts")) continue
    let code = fs.readFileSync(path.join(srcDir, f), "utf8")
    code = ts.transpileModule(code, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
    code = code.replace(/from "(\.\/[a-z-]+)"/g, 'from "$1.mjs"')
    fs.writeFileSync(path.join(dir, f.replace(/\.ts$/, ".mjs")), code)
  }
  // `motion/react` is only imported for a type, so it is erased; nothing else is external.
  const t = {}
  for (const n of ["types", "presets", "css", "motion", "typescale", "values", "fonts", "ui-color"]) {
    t[n] = await import(pathToFileURL(path.join(dir, `${n}.mjs`)).href)
  }
  return t
}

