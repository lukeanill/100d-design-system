const CATEGORY_ORDER = ["Tokens", "Components", "Special FX Components", "Animation", "Other"]

function storyId(title, exportName) {
  // Storybook sanitises the title, and turns the export name into words the way lodash startCase does (digits split off: Letter3dSwap -> letter-3-d-swap)
  const clean = (x) => x.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "")
  const words = (x) => (x.match(/[A-Z]+(?![a-z])|[A-Z]?[a-z]+|\d+/g) ?? [x]).join(" ")
  return `${clean(title)}--${clean(words(exportName))}`
}

function readStories() {
  const map = new Map() // component file (abs, no ext) -> {title, id, stories[]}
  for (const f of walk(SRC, (p) => p.endsWith(".stories.tsx"))) {
    const text = fs.readFileSync(f, "utf8")
    const title = text.match(/\btitle:\s*["'`]([^"'`]+)["'`]/)?.[1]
    if (!title) continue
    const exports = [...text.matchAll(/^export const ([A-Z][A-Za-z0-9]*)\b/gm)].map((m) => m[1]).filter((n) => !/^(meta|default)$/i.test(n))
    // stories exported from `export const X: Story`; skip helpers that are not stories (they rarely start with Story type)
    const stories = exports.filter((n) => new RegExp(`export const ${n}\\s*(:\\s*(Story|StoryObj)[^=]*)?=`).test(text))
    const base = f.replace(/\.stories\.tsx$/, "")
    map.set(base, { title, stories, file: f })
  }
  return map
}

function categoryOf(title, file) {
  const top = title.split("/")[0]
  if (CATEGORY_ORDER.includes(top)) return top
  if (/Customers|Hotels|onboarding|Update available|MCP/i.test(title)) return "Other"
  if (file.includes("/transitions/") || file.includes("/fancy/") || file.includes("/backgrounds/") || file.includes("animate-ui/primitives")) return "Animation"
  return "Components"
}

function buildProgram() {
  const cfgPath = path.join(UI, "tsconfig.json")
  const cfg = ts.getParsedCommandLineOfConfigFile(cfgPath, {}, { ...ts.sys, onUnRecoverableConfigFileDiagnostic: () => {} })
  const roots = walk(path.join(SRC, "components"), (f) => /\.tsx$/.test(f) && !/\.stories\./.test(f))
  const program = ts.createProgram({ rootNames: roots, options: { ...cfg.options, noEmit: true, skipLibCheck: true } })
  return { program, checker: program.getTypeChecker(), roots }
}

const SKIP_DECL = /node_modules\/(@types\/react|@types\/react-dom|typescript|csstype|@types\/node)\b|node_modules\/\.pnpm\/(@types\+react|typescript|csstype)/
const LIB_NOTE = /node_modules/

function propsOf(checker, sourceFile) {
  const moduleSym = checker.getSymbolAtLocation(sourceFile)
  if (!moduleSym) return []
  const results = []
  for (const sym of checker.getExportsOfModule(moduleSym)) {
    const name = sym.getName()
    if (!/^[A-Z]/.test(name)) continue
    const decl = sym.valueDeclaration ?? sym.declarations?.[0]
    if (!decl) continue
    // follow re-exports
    const type = checker.getTypeOfSymbolAtLocation(sym, decl)
    const sigs = type.getCallSignatures()
    if (!sigs.length) continue
    const param = sigs[0].getParameters()[0]
    const props = []
    let inherited = new Set()
    if (param) {
      const pType = checker.getTypeOfSymbolAtLocation(param, param.valueDeclaration ?? decl)
      for (const p of checker.getPropertiesOfType(pType)) {
        const pd = p.valueDeclaration ?? p.declarations?.[0]
        const file = pd?.getSourceFile().fileName ?? ""
        // no declaration: a property synthesised by Omit/Pick over a library type, so it is inherited
        if (!pd) { inherited.add("the underlying element or library"); continue }
        if (SKIP_DECL.test(file)) continue
        if (LIB_NOTE.test(file) && !/class-variance-authority/.test(file)) {
          const lib = file.match(/node_modules\/(?:\.pnpm\/[^/]+\/node_modules\/)?((?:@[^/]+\/)?[^/]+)/)?.[1]
          if (lib) inherited.add(lib)
          continue
        }
        let typeText = ""
        try {
          const pt = checker.getTypeOfSymbolAtLocation(p, pd ?? decl)
          typeText = checker.typeToString(checker.getNonNullableType(pt), undefined, ts.TypeFormatFlags.NoTruncation | ts.TypeFormatFlags.UseAliasDefinedOutsideCurrentScope)
        } catch {
          typeText = "?"
        }
        if (typeText.length > 110) typeText = typeText.slice(0, 107) + "…"
        const optional = !!(p.flags & ts.SymbolFlags.Optional)
        const doc = ts.displayPartsToString(p.getDocumentationComment(checker)).replace(/\s+/g, " ").trim()
        props.push({ name: p.getName(), type: typeText, optional, doc })
      }
    }
    results.push({ name, props, inherited: [...inherited] })
  }
  return results
}

function buildImportGraph() {
  // component file (abs, no ext) -> { web: Set(files), ui: Set(files) }
  const used = new Map()
  const files = [
    ...walk(SRC, (f) => /\.(tsx|ts)$/.test(f) && !/\.(stories|test)\./.test(f)),
    ...walk(WEB, (f) => /\.(tsx|ts)$/.test(f) && !/\.(test)\./.test(f)),
  ]
  const storyFiles = walk(SRC, (f) => f.endsWith(".stories.tsx"))
  const touch = (target, from, kind) => {
    if (!used.has(target)) used.set(target, { web: new Set(), ui: new Set(), stories: new Set() })
    used.get(target)[kind].add(from)
  }
  const resolve = (spec, fromFile) => {
    let p
    if (spec.startsWith("@workspace/ui/") || spec.startsWith("@lukeanill/ui/")) p = path.join(SRC, spec.replace(/^@[a-z]+\/ui\//, ""))
    else if (spec.startsWith(".")) p = path.resolve(path.dirname(fromFile), spec)
    else return null
    for (const cand of [p, p + ".tsx", p + ".ts", path.join(p, "index.tsx")]) if (fs.existsSync(cand) && fs.statSync(cand).isFile()) return cand.replace(/\.tsx?$/, "")
    return null
  }
  for (const f of [...files, ...storyFiles]) {
    const text = fs.readFileSync(f, "utf8")
    const isStory = f.endsWith(".stories.tsx")
    const inWeb = f.startsWith(WEB)
    for (const m of text.matchAll(/(?:from|import)\s*\(?\s*["']([^"']+)["']/g)) {
      const target = resolve(m[1], f)
      if (!target || target === f.replace(/\.tsx?$/, "")) continue
      touch(target, f, isStory ? "stories" : inWeb ? "web" : "ui")
    }
  }
  return used
}

// Where a web-app file sits in the product.
const WEB_PLACES = [
  [/themer\/ProductPreview/, "Themer preview: the Coeurdes Alpes product page"],
  [/themer\//, "Themer (/themes)"],
  [/Showcase|LinkTile|Pill\b/, "Homepage (/)"],
  [/Preview\.tsx/, "Homepage preview"],
  [/SlopesPhone/, "Slopes phone demo"],
  [/Tokens\.tsx/, "Tokens page (/tokens)"],
  [/History/, "History page (/history)"],
  [/explore\//, "Explore"],
  [/main\.tsx/, "App shell (every page)"],
]
const place = (f) => WEB_PLACES.find(([re]) => re.test(f))?.[1] ?? rel(f)

function componentsDocs() {
  const { program, checker, roots } = buildProgram()
  const stories = readStories()
  const used = buildImportGraph()
  const index = []
  for (const file of roots.sort()) {
    const base = file.replace(/\.tsx$/, "")
    const sf = program.getSourceFile(file)
    if (!sf) continue
    const comps = propsOf(checker, sf)
    const story = stories.get(base)
    const title = story?.title
    const category = title ? categoryOf(title, file) : categoryOf("", file)
    const u = used.get(base)
    const webPlaces = u ? [...new Set([...u.web].map(place))] : []
    const importPath = "@workspace/ui/" + rel(base).replace(/^packages\/ui\/src\//, "")
    const firstStory = story?.stories[0]
    index.push({
      file,
      base,
      importPath,
      title: title ?? null,
      category,
      sub: title ? title.split("/").slice(1, -1).join("/") || "General" : "Not in Storybook",
      name: title ? title.split("/").pop() : path.basename(base),
      storyUrl: title && firstStory ? `${STORYBOOK}?path=/story/${storyId(title, firstStory)}` : null,
      stories: story?.stories ?? [],
      comps,
      webPlaces,
      uiUsers: u ? [...u.ui].map((f) => path.basename(f).replace(/\.tsx?$/, "")).sort() : [],
      hasStory: !!story,
    })
  }
  // stories whose file has no component of the same name (token sheets, motion demos)
  const have = new Set(index.map((e) => e.base))
  for (const [base, story] of stories) {
    if (have.has(base)) continue
    const title = story.title
    const first = story.stories[0]
    index.push({
      file: story.file, base, importPath: "(story only, no component file)", title,
      category: categoryOf(title, story.file), sub: title.split("/").slice(1, -1).join("/") || "General",
      name: title.split("/").pop(), storyUrl: first ? `${STORYBOOK}?path=/story/${storyId(title, first)}` : null,
      stories: story.stories, comps: [], webPlaces: [], uiUsers: [], hasStory: true,
    })
  }
  // drop hook/helper-only files with no components and no story
  const useful = index.filter((e) => e.comps.length || e.hasStory)
  return { index, useful }
}

function renderComponent(e) {
  const o = []
  o.push(`### ${e.name}`, "")
  o.push(`- File: \`${rel(e.file)}\``)
  o.push(`- Import: ${e.importPath.startsWith("(") ? e.importPath : `\`${e.importPath}\``}`)
  o.push(`- Storybook: ${e.storyUrl ? `[${e.title}](${e.storyUrl})` : "no story yet"}${e.stories.length > 1 ? ` (stories: ${e.stories.join(", ")})` : ""}`)
  o.push(`- Used in the web app: ${e.webPlaces.length ? e.webPlaces.join("; ") : "not used in apps/web (Storybook only)"}`)
  o.push(`- Used by other components: ${e.uiUsers.length ? e.uiUsers.slice(0, 8).join(", ") + (e.uiUsers.length > 8 ? ` (+${e.uiUsers.length - 8})` : "") : "none"}`)
  for (const c of e.comps) {
    if (e.comps.length > 1) o.push("", `**\`${c.name}\`**`)
    if (c.props.length) {
      o.push("", "| Prop | Type | Required | Note |", "|---|---|---|---|")
      for (const p of c.props) o.push(`| \`${p.name}\` | \`${esc(p.type)}\` | ${p.optional ? "no" : "yes"} | ${esc(p.doc)} |`)
    } else {
      o.push("", "_No props of its own._")
    }
    if (c.inherited.length) o.push("", `Also accepts the props of ${c.inherited.map((l) => `\`${l}\``).join(", ")} and standard HTML attributes.`)
  }
  o.push("")
  return o.join("\n")
}

function writeComponentDocs() {
  const { index, useful } = componentsDocs()
  const section = (name, filter) => {
    const items = useful.filter(filter)
    const bySub = new Map()
    for (const e of items) {
      const key = e.sub || "General"
      if (!bySub.has(key)) bySub.set(key, [])
      bySub.get(key).push(e)
    }
    return { items, bySub }
  }
  const comp = section("components", (e) => e.category === "Components" || e.category === "Special FX Components" || e.category === "Tokens" || e.category === "Other")
  const anim = section("animations", (e) => e.category === "Animation")

  const emit = (kind, title, intro, sec, withGroupFiles) => {
    const idx = [GENERATED, "", `# ${title}`, "", intro, "", `Total: ${sec.items.length} entries. Storybook base: ${STORYBOOK}. Detail files (props, usage, link) are in \`references/${kind}/\`; read only the group you need.`, ""]
    for (const [sub, items] of [...sec.bySub].sort(([a], [b]) => a.localeCompare(b))) {
      const slug = sub.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "general"
      idx.push(`## ${sub}`, "", `Detail: \`references/${kind}/${slug}.md\``, "", "| Name | Import | Storybook | Used in web app |", "|---|---|---|---|")
      for (const e of items.sort((a, b) => a.name.localeCompare(b.name))) {
        idx.push(`| ${e.name} | ${e.importPath.startsWith("(") ? "story only" : `\`${e.importPath.replace("@workspace/ui/", "")}\``} | ${e.storyUrl ? `[story](${e.storyUrl})` : "—"} | ${e.webPlaces.length ? esc(e.webPlaces.slice(0, 2).join("; ")) : "—"} |`)
      }
      idx.push("")
      const detail = [GENERATED, "", `# ${title}: ${sub}`, ""]
      for (const e of items.sort((a, b) => a.name.localeCompare(b.name))) detail.push(renderComponent(e))
      write(path.join(OUT, kind, `${slug}.md`), detail.join("\n"))
    }
    write(path.join(OUT, `${kind}.md`), idx.join("\n"))
  }
  fs.rmSync(path.join(OUT, "components"), { recursive: true, force: true })
  fs.rmSync(path.join(OUT, "animations"), { recursive: true, force: true })
  emit("components", "Components", "Every component in `packages/ui/src/components` (import `@workspace/ui/components/<path>`; published as `@lukeanill/ui/components/<path>`). Groups follow the Storybook sidebar.", comp)
  emit("animations", "Animations", "Animated components and effects: page transitions, text effects, interactions, backgrounds, buttons. These live under \"Animation\" in Storybook. The motion tokens that drive them are in `tokens.md`; the theme choices in `themes.md` (motion, feel).", anim)
  const withoutStory = useful.filter((e) => !e.hasStory).map((e) => rel(e.file))
  return { total: useful.length, withoutStory }
}

